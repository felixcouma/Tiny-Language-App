/*
 * Generate docs/IMAGE_PROMPTS.md — a consistent style + per-item prompt + filename
 * for every photo item, ready for nano-banana (Gemini image) generation.
 * Run: node scripts/gen-image-prompts.mjs
 */
import { writeFileSync } from 'node:fs'
import { WORLDS } from '../src/data/content.js'

const STYLE =
  'Flat vector cartoon illustration for a toddler learning app. Soft rounded shapes, ' +
  'thick clean dark outlines, bright cheerful pastel colours, simple solid off-white ' +
  'background, single centered subject, no text or letters, friendly, cute, wholesome, ' +
  'consistent children’s-book style, high quality.'

function subjectFor(world, item) {
  const w = item.word.toLowerCase()
  switch (world.id) {
    case 'safari-island':
    case 'music-forest':
      return `a cute friendly ${w}, full body, big happy eyes, gentle smile`
    case 'my-body':
      return `a cheerful cartoon toddler clearly showing their ${w}, the ${w} prominent and obvious`
    case 'things-i-do':
      return `a happy cartoon toddler ${w}, clear simple action`
    case 'home-village':
      if (w === 'bath') return 'a cute cartoon bathtub full of bubbles'
      return `a single cute cartoon ${w}, centered`
    default:
      return `a cute cartoon ${w}`
  }
}

// Photo items only (skip colour swatches, numbers, family portraits); dedupe by filename key.
const rows = new Map()
for (const world of WORLDS) {
  for (const item of world.items) {
    const isPhoto = item.numeral == null && !item.swatch && !item.portrait
    if (!isPhoto) continue
    const key = item.sound
    if (rows.has(key)) continue
    rows.set(key, { key, word: item.word, world: world.name, subject: subjectFor(world, item) })
  }
}

const lines = []
lines.push('# 🖼️ Image generation prompts (nano-banana / Gemini)')
lines.push('')
lines.push('Auto-generated by `node scripts/gen-image-prompts.mjs`. One cohesive style, one')
lines.push('prompt per item. Generate locally, then drop the files into `public/images/` — the')
lines.push('app uses them automatically (falling back to Wikimedia for any not yet made).')
lines.push('')
lines.push('## Setup (local, one-time)')
lines.push('```bash')
lines.push('npm install -g @google/gemini-cli')
lines.push('export NANOBANANA_GEMINI_API_KEY="your-key"   # from Google AI Studio')
lines.push('gemini extensions install https://github.com/gemini-cli-extensions/nanobanana')
lines.push('git clone https://github.com/kkoppenhaver/cc-nano-banana ~/.claude/skills/nano-banana')
lines.push('```')
lines.push('')
lines.push('## Workflow')
lines.push('1. In **local Claude Code**, ask it to generate each image below with the **same seed**')
lines.push('   (e.g. `--seed 7`) so the style stays consistent.')
lines.push('2. Save each as `public/images/<filename>` (PNG, roughly square, ~640px).')
lines.push('3. **Review every image** for toddler-friendliness before committing.')
lines.push('4. `git add public/images && git commit && git push` — done.')
lines.push('')
lines.push('## Shared style (prepend to every prompt)')
lines.push('```')
lines.push(STYLE)
lines.push('```')
lines.push('')
lines.push(`## ${rows.size} images`)
lines.push('')
lines.push('| Filename | Word | World | Prompt (style + subject) |')
lines.push('| --- | --- | --- | --- |')
for (const r of rows.values()) {
  lines.push(`| \`${r.key}.png\` | ${r.word} | ${r.world} | ${STYLE} Subject: ${r.subject}. |`)
}
lines.push('')

writeFileSync(new URL('../docs/IMAGE_PROMPTS.md', import.meta.url), lines.join('\n'))
console.log(`Wrote docs/IMAGE_PROMPTS.md with ${rows.size} prompts.`)
